//! The embedded 8x8 bitmap glyph atlas (M4 pixel foundation, Part 1).
//!
//! [`BitmapFont`](super::BitmapFont)'s metrics-only geometry (`vga_8x16`, an
//! 8-wide/16-tall cell) has no glyph bitmaps of its own — see that module's
//! doc comment for why raster data was deliberately deferred to this exact
//! packet. This module supplies the missing pixels: a public-domain 8x8
//! font, embedded as a compiled-in Rust table, looked up per `char`.
//!
//! ## Fonts / licenses
//!
//! - **Font**: `font8x8_basic` (128 glyphs, ASCII 0x00-0x7F, 8 bytes/glyph).
//! - **Source**: <https://raw.githubusercontent.com/dhepper/font8x8/master/font8x8_basic.h>
//!   (repository: <https://github.com/dhepper/font8x8>, by Daniel Hepper).
//! - **License**: Public Domain, per that file's own header comment. It in
//!   turn credits Marcel Sondaar / IBM's original public-domain VGA fonts.
//!   Public Domain is compatible with embedding in this project (no
//!   attribution or copyleft obligation), so no additional license text
//!   needs to ship in the binary.
//! - This note is duplicated in `REPORT.md`'s "Fonts / licenses" section per
//!   the packet brief's license-check requirement.
//!
//! ## Bit order (pins the raster — read before touching [`FONT8X8_BASIC`])
//!
//! Each glyph is 8 bytes, one byte per pixel row (row 0 = top). Within a
//! byte, **bit 0 (the LSB) is the LEFTMOST pixel** of that row (bit 6 is the
//! rightmost of the 7 columns the font actually draws into; bit 7 is always
//! `0` in this table — the font is authored on a 7-wide glyph inside an
//! 8-wide cell, with the 8th column left blank for inter-glyph spacing).
//! Confirmed empirically against 'A' (`U+0041`, index `0x41`): its row bytes
//! (`0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00`) decode, under this bit
//! order, to a recognizable capital-A silhouette (a narrow peak widening
//! into two legs, joined by a full-width crossbar) — the opposite bit order
//! would instead render a mirror-image glyph.
//!
//! ## Coverage and fallback
//!
//! The table covers `U+0000..=U+007F` (the full ASCII range the source file
//! ships, control chars included — those simply render as their authored
//! shape, mostly blank). [`lookup`] is total over *all* of `char`: any
//! scalar value outside `0x00..=0x7F` (Latin-1 supplement, CJK, emoji,
//! unassigned/private-use, ...) returns [`FALLBACK_GLYPH`], a small hollow
//! "tofu" box, rather than panicking or silently vanishing — a real font's
//! usual "missing glyph" convention, and easy to spot in a golden PNG.

